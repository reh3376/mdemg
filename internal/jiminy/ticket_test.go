func TestTicketManager_IssueAndValidate(t *testing.T) {
	tm := NewTicketManager("test-secret-key-32bytes!!", 4, 0)

	payload := TicketPayload{
		SpaceID:   "test-space",
		SessionID: "test-session",
		LastSeq:   42,
		TrustScore: 0.75,
		EscalationSnapshot: map[string]EscalationEntry{
			"node-1": {NodeID: "node-1", Level: EscalationWarned, IgnoreCount: 2},
			"node-2": {NodeID: "node-2", Level: EscalationEscalated, IgnoreCount: 4},
		},
		ActiveConstraintIDs: []string{"node-1", "node-2"},
		ConversationPhase:   "active",
	}

	ticket, err := tm.IssueTicket(payload)
	if err != nil {
		t.Fatalf("IssueTicket failed: %v", err)
	}
	if ticket == nil {
		t.Fatal("ticket is nil")
	}
	if ticket.Signature == "" {
		t.Fatal("ticket signature is empty")
	}

	// Validate round-trip
	restored, err := tm.ValidateTicket(ticket)
	if err != nil {
		t.Fatalf("ValidateTicket failed: %v", err)
	}
	if restored.Version != J17Version {
		t.Errorf("version = %q, want %q", restored.Version, J17Version)
	}
	if restored.SpaceID != "test-space" {
		t.Errorf("space_id = %q, want %q", restored.SpaceID, "test-space")
	}
	if restored.SessionID != "test-session" {
		t.Errorf("session_id = %q, want %q", restored.SessionID, "test-session")
	}
	if restored.LastSeq != 42 {
		t.Errorf("last_seq = %d, want 42", restored.LastSeq)
	}
	if restored.TrustScore != 0.75 {
		t.Errorf("trust_score = %f, want 0.75", restored.TrustScore)
	}
	if len(restored.EscalationSnapshot) != 2 {
		t.Errorf("escalation_snapshot len = %d, want 2", len(restored.EscalationSnapshot))
	}
	if restored.EscalationSnapshot["node-1"].Level != EscalationWarned {
		t.Errorf("node-1 level = %q, want %q", restored.EscalationSnapshot["node-1"].Level, EscalationWarned)
	}
}

func TestTicketManager_TamperDetection(t *testing.T) {
	tm := NewTicketManager("test-secret-key-32bytes!!", 4, 0)

	payload := TicketPayload{
		SpaceID:   "test-space",
		SessionID: "test-session",
		LastSeq:   10,
	}

	ticket, err := tm.IssueTicket(payload)
	if err != nil {
		t.Fatalf("IssueTicket failed: %v", err)
	}

	// Tamper with payload
	var p TicketPayload
	_ = json.Unmarshal(ticket.Payload, &p)
	p.TrustScore = 1.0 // try to boost trust
	tampered, _ := json.Marshal(p)
	ticket.Payload = tampered

	_, err = tm.ValidateTicket(ticket)
	if err == nil {
		t.Fatal("expected validation to fail for tampered ticket")
	}
}

func TestTicketManager_TTLExpiry(t *testing.T) {
	tm := NewTicketManager("test-secret", 1, 0) // 1 hour TTL

	payload := TicketPayload{
		SpaceID:   "test-space",
		SessionID: "test-session",
	}

	ticket, err := tm.IssueTicket(payload)
	if err != nil {
		t.Fatalf("IssueTicket failed: %v", err)
	}

	// Manually expire the ticket by modifying the payload's IssuedAt
	var p TicketPayload
	_ = json.Unmarshal(ticket.Payload, &p)
	p.IssuedAt = time.Now().Add(-2 * time.Hour) // 2 hours ago
	expired, _ := json.Marshal(p)

	// Re-sign with the correct key to isolate TTL check from tamper check
	ticket.Payload = expired
	ticket.Signature = tm.sign(expired)

	_, err = tm.ValidateTicket(ticket)
	if err == nil {
		t.Fatal("expected validation to fail for expired ticket")
	}
}

