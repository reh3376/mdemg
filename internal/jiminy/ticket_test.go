func TestTicketManager_RestoreEscalation(t *testing.T) {
	tm := NewTicketManager("test-secret", 4, 0)

	// Create escalation tracker and populate state
	cfg := defaultTestConfig()
	tracker := NewEscalationTracker(cfg)

	// Simulate some escalation state
	tracker.RecordSurface("sess-1", "node-1")
	tracker.RecordOutcome("sess-1", "node-1", OutcomeIgnored) // ignore 1
	tracker.RecordOutcome("sess-1", "node-1", OutcomeIgnored) // ignore 2 → warned

	level := tracker.GetState("sess-1", "node-1")
	if level != EscalationWarned {
		t.Fatalf("pre-ticket level = %q, want %q", level, EscalationWarned)
	}

	// Export state and create ticket
	states := tracker.ExportState("sess-1")
	payload := TicketPayload{
		SpaceID:            "test-space",
		SessionID:          "sess-1",
		LastSeq:            10,
		EscalationSnapshot: states,
	}

	ticket, err := tm.IssueTicket(payload)
	if err != nil {
		t.Fatalf("IssueTicket failed: %v", err)
	}

	// Create fresh tracker (simulating context reset)
	newTracker := NewEscalationTracker(cfg)
	freshLevel := newTracker.GetState("sess-1", "node-1")
	if freshLevel != EscalationInactive {
		t.Fatalf("fresh tracker should have inactive, got %q", freshLevel)
	}

	// Restore from ticket
	_, err = tm.RestoreFromTicket(ticket, newTracker)
	if err != nil {
		t.Fatalf("RestoreFromTicket failed: %v", err)
	}

	// Verify escalation state was restored
	restoredLevel := newTracker.GetState("sess-1", "node-1")
	if restoredLevel != EscalationWarned {
		t.Errorf("restored level = %q, want %q", restoredLevel, EscalationWarned)
	}
}

