func TestTicketManager_LRUEviction(t *testing.T) {
	tm := NewTicketManager("test-secret", 4, 3) // maxSize = 3

	// Issue tickets for 5 different sessions
	for i := 1; i <= 5; i++ {
		_, err := tm.IssueTicket(TicketPayload{
			SpaceID:   "test-space",
			SessionID: fmt.Sprintf("sess-%d", i),
			LastSeq:   int64(i),
		})
		if err != nil {
			t.Fatalf("IssueTicket sess-%d failed: %v", i, err)
		}
	}

	// Only 3 tickets should remain (sess-3, sess-4, sess-5)
	tm.mu.RLock()
	mapLen := len(tm.lastTickets)
	listLen := tm.lruList.Len()
	tm.mu.RUnlock()

	if mapLen != 3 {
		t.Errorf("lastTickets map size = %d, want 3", mapLen)
	}
	if listLen != 3 {
		t.Errorf("lruList length = %d, want 3", listLen)
	}

	// Oldest sessions (sess-1, sess-2) should be evicted
	if tk := tm.GetLastTicket("sess-1"); tk != nil {
		t.Error("sess-1 should have been evicted")
	}
	if tk := tm.GetLastTicket("sess-2"); tk != nil {
		t.Error("sess-2 should have been evicted")
	}

	// Newest sessions should still be present
	for i := 3; i <= 5; i++ {
		if tk := tm.GetLastTicket(fmt.Sprintf("sess-%d", i)); tk == nil {
			t.Errorf("sess-%d should still be present", i)
		}
	}

	// Re-issuing for existing session should not grow the map
	_, err := tm.IssueTicket(TicketPayload{
		SpaceID:   "test-space",
		SessionID: "sess-3",
		LastSeq:   99,
	})
	if err != nil {
		t.Fatalf("re-issue sess-3 failed: %v", err)
	}

	tm.mu.RLock()
	finalLen := len(tm.lastTickets)
	tm.mu.RUnlock()

	if finalLen != 3 {
		t.Errorf("after re-issue, map size = %d, want 3", finalLen)
	}
}

