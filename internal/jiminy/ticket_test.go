func TestSequenceTracker_RecordAndReplay(t *testing.T) {
	st := NewSequenceTracker(100)

	// Record 5 events
	for i := 0; i < 5; i++ {
		st.RecordGuidance("space-1", "sess-1", i+1, "")
	}

	if st.Count() != 5 {
		t.Errorf("count = %d, want 5", st.Count())
	}

	// Replay all events since seq 0
	events := st.EventsSince(0, 50)
	if len(events) != 5 {
		t.Fatalf("EventsSince(0) = %d events, want 5", len(events))
	}
	if events[0].Seq != 1 {
		t.Errorf("first event seq = %d, want 1", events[0].Seq)
	}
	if events[4].Seq != 5 {
		t.Errorf("last event seq = %d, want 5", events[4].Seq)
	}

	// Replay from seq 3 onwards
	events = st.EventsSince(3, 50)
	if len(events) != 2 {
		t.Fatalf("EventsSince(3) = %d events, want 2", len(events))
	}
	if events[0].Seq != 4 {
		t.Errorf("first replayed seq = %d, want 4", events[0].Seq)
	}
}

func TestSequenceTracker_RingBufferOverflow(t *testing.T) {
	st := NewSequenceTracker(5) // small buffer

	// Record 8 events — should wrap around
	for i := 0; i < 8; i++ {
		st.RecordGuidance("space-1", "sess-1", 1, "")
	}

	if st.Count() != 5 {
		t.Errorf("count = %d, want 5 (buffer size)", st.Count())
	}

	// Only events 4-8 should be in buffer
	events := st.EventsSince(0, 50)
	if len(events) != 5 {
		t.Fatalf("EventsSince(0) = %d events, want 5", len(events))
	}
	if events[0].Seq != 4 {
		t.Errorf("oldest event seq = %d, want 4", events[0].Seq)
	}
	if events[4].Seq != 8 {
		t.Errorf("newest event seq = %d, want 8", events[4].Seq)
	}
}

